package com.mealplanner.presentation.ui.grocery

import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.mealplanner.data.repository.GroceryRepository
import com.mealplanner.domain.model.GroceryItem
import dagger.hilt.android.lifecycle.HiltViewModel
import kotlinx.coroutines.flow.*
import kotlinx.coroutines.launch
import javax.inject.Inject

data class GroceryUiState(
    val isLoading: Boolean = true,
    val groupedItems: Map<String, List<GroceryItem>> = emptyMap(),
    val totalItems: Int = 0,
    val checkedItems: Int = 0,
    val error: String? = null
)

@HiltViewModel
class GroceryViewModel @Inject constructor(
    private val repository: GroceryRepository
) : ViewModel() {

    val uiState: StateFlow<GroceryUiState> = repository.getAllGroceryItems()
        .map { items ->
            val grouped = items.groupBy { it.category }
                .toSortedMap(compareBy { if (it == "Other") "ZZZ" else it })
            GroceryUiState(
                isLoading = false,
                groupedItems = grouped,
                totalItems = items.size,
                checkedItems = items.count { it.isChecked }
            )
        }
        .catch { e -> emit(GroceryUiState(isLoading = false, error = e.message)) }
        .stateIn(viewModelScope, SharingStarted.WhileSubscribed(5000), GroceryUiState())

    fun toggleItem(item: GroceryItem) {
        viewModelScope.launch { repository.toggleChecked(item.id, !item.isChecked) }
    }

    fun addItem(name: String, quantity: Double, unit: String) {
        viewModelScope.launch {
            repository.insertGroceryItem(
                GroceryItem(name = name, quantity = quantity, unit = unit, isManuallyAdded = true)
            )
        }
    }

    fun deleteItem(item: GroceryItem) {
        viewModelScope.launch { repository.deleteGroceryItem(item) }
    }

    fun clearChecked() {
        viewModelScope.launch { repository.deleteCheckedItems() }
    }

    fun clearAll() {
        viewModelScope.launch { repository.clearAll() }
    }

    fun getExportText(): String {
        val state = uiState.value
        val sb = StringBuilder()
        sb.append("🛒 My Grocery List\n")
        sb.append("-------------------\n\n")
        
        state.groupedItems.forEach { (category, items) ->
            sb.append("[$category]\n")
            items.forEach { item ->
                val status = if (item.isChecked) "[x]" else "[ ]"
                sb.append("$status ${item.name}: ${item.quantity} ${item.unit}\n")
            }
            sb.append("\n")
        }
        
        sb.append("Generated by Meal Planner App")
        return sb.toString()
    }
}
